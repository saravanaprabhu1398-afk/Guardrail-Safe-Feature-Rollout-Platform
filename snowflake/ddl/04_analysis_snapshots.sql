-- Phase 4: immutable integrity and statistical-analysis snapshots.
-- Run as GUARDRAIL_ENGINEER after snowflake/bootstrap/01_platform.sql.

USE ROLE GUARDRAIL_ENGINEER;
USE WAREHOUSE GUARDRAIL_TRANSFORM_WH;
USE DATABASE GUARDRAIL;

CREATE TABLE IF NOT EXISTS CONTROL.EXPERIMENT_HEALTH_SNAPSHOTS (
  HEALTH_SNAPSHOT_ID STRING NOT NULL,
  EXPERIMENT_ID STRING NOT NULL,
  ALLOCATION_VERSION NUMBER(9, 0) NOT NULL,
  EXPECTED_TREATMENT_PERCENTAGE NUMBER(3, 0) NOT NULL,
  INTEGRITY_POLICY_VERSION STRING NOT NULL,
  INTEGRITY_POLICY VARIANT NOT NULL,
  INTEGRITY_EVIDENCE VARIANT NOT NULL,
  HEALTH_REPORT VARIANT NOT NULL,
  CONTENT_HASH STRING NOT NULL,
  CREATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_EXPERIMENT_HEALTH_SNAPSHOTS
    PRIMARY KEY (HEALTH_SNAPSHOT_ID) NOT ENFORCED
)
COMMENT = 'Immutable content-addressed experiment-integrity evidence and results';

CREATE TABLE IF NOT EXISTS CONTROL.EXPERIMENT_ANALYSIS_SNAPSHOTS (
  ANALYSIS_SNAPSHOT_ID STRING NOT NULL,
  HEALTH_SNAPSHOT_ID STRING NOT NULL,
  EXPERIMENT_ID STRING NOT NULL,
  ALLOCATION_VERSION NUMBER(9, 0) NOT NULL,
  ANALYSIS_POLICY_VERSION STRING NOT NULL,
  ANALYSIS_POLICY VARIANT NOT NULL,
  ANALYSIS_EVIDENCE VARIANT,
  ANALYSIS_REPORT VARIANT NOT NULL,
  CONTENT_HASH STRING NOT NULL,
  CREATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_EXPERIMENT_ANALYSIS_SNAPSHOTS
    PRIMARY KEY (ANALYSIS_SNAPSHOT_ID) NOT ENFORCED,
  CONSTRAINT FK_ANALYSIS_HEALTH_SNAPSHOT
    FOREIGN KEY (HEALTH_SNAPSHOT_ID)
    REFERENCES CONTROL.EXPERIMENT_HEALTH_SNAPSHOTS (HEALTH_SNAPSHOT_ID) NOT ENFORCED
)
COMMENT = 'Immutable content-addressed statistical inputs, policy, output, and health lineage';

SELECT
  CURRENT_ROLE(),
  CURRENT_WAREHOUSE(),
  COUNT_IF(TABLE_NAME IN (
    'EXPERIMENT_HEALTH_SNAPSHOTS',
    'EXPERIMENT_ANALYSIS_SNAPSHOTS'
  ))
FROM GUARDRAIL.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'CONTROL';
