CREATE OR REPLACE VIEW CLEAN.PRODUCT_EVENTS_CLASSIFIED
  COMMENT = 'Raw events with deterministic contract-validation results'
AS
SELECT
  raw_event.*,
  CASE
    WHEN raw_event.EVENT_ID IS NULL OR raw_event.EVENT_ID = ''
      THEN 'MISSING_EVENT_ID'
    WHEN contract.EVENT_NAME IS NULL
      THEN 'UNSUPPORTED_EVENT_CONTRACT'
    WHEN NULLIF(raw_event.PAYLOAD:user_id::STRING, '') IS NULL
      THEN 'MISSING_USER_ID'
    WHEN NULLIF(raw_event.PAYLOAD:session_id::STRING, '') IS NULL
      THEN 'MISSING_SESSION_ID'
    WHEN NULLIF(raw_event.PAYLOAD:experiment_id::STRING, '') IS NULL
      THEN 'MISSING_EXPERIMENT_ID'
    WHEN raw_event.PAYLOAD:variant_id::STRING NOT IN ('control', 'treatment')
      THEN 'INVALID_VARIANT_ID'
    WHEN raw_event.EVENT_TIMESTAMP IS NULL
      THEN 'INVALID_EVENT_TIMESTAMP'
    WHEN raw_event.RECEIVED_TIMESTAMP IS NULL
      THEN 'INVALID_RECEIVED_TIMESTAMP'
    WHEN TYPEOF(raw_event.PAYLOAD:attributes) <> 'OBJECT'
      THEN 'INVALID_ATTRIBUTES'
    ELSE NULL
  END AS REJECTION_REASON
FROM RAW.PRODUCT_EVENTS AS raw_event
LEFT JOIN CONFIG.EVENT_CONTRACTS AS contract
  ON raw_event.EVENT_NAME = contract.EVENT_NAME
 AND raw_event.EVENT_VERSION = contract.EVENT_VERSION
 AND contract.CONTRACT_STATUS = 'ACTIVE';

CREATE OR REPLACE PROCEDURE CONTROL.PROCESS_INGESTION_BATCH(
  P_BATCH_ID STRING,
  P_CHANNEL_ID STRING,
  P_FIRST_OFFSET NUMBER,
  P_LAST_OFFSET NUMBER,
  P_RECORDS_SUBMITTED NUMBER
)
RETURNS VARIANT
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  V_RAW_COUNT NUMBER DEFAULT 0;
  V_VALIDATED_COUNT NUMBER DEFAULT 0;
  V_REJECTED_COUNT NUMBER DEFAULT 0;
  V_DUPLICATE_COUNT NUMBER DEFAULT 0;
BEGIN
  MERGE INTO CLEAN.PRODUCT_EVENTS_VALIDATED AS target
  USING (
    SELECT
      INGESTION_ID,
      BATCH_ID,
      EVENT_ID,
      EVENT_NAME,
      EVENT_VERSION,
      PAYLOAD:user_id::STRING AS USER_ID,
      PAYLOAD:anonymous_id::STRING AS ANONYMOUS_ID,
      PAYLOAD:session_id::STRING AS SESSION_ID,
      PAYLOAD:experiment_id::STRING AS EXPERIMENT_ID,
      PAYLOAD:variant_id::STRING AS VARIANT_ID,
      EVENT_TIMESTAMP,
      TRY_TO_TIMESTAMP_TZ(PAYLOAD:sent_timestamp::STRING) AS SENT_TIMESTAMP,
      RECEIVED_TIMESTAMP,
      SOURCE,
      PAYLOAD:attributes AS ATTRIBUTES,
      PAYLOAD_HASH
    FROM CLEAN.PRODUCT_EVENTS_CLASSIFIED
    WHERE BATCH_ID = :P_BATCH_ID
      AND REJECTION_REASON IS NULL
  ) AS source
  ON target.INGESTION_ID = source.INGESTION_ID
  WHEN NOT MATCHED THEN INSERT (
    INGESTION_ID, BATCH_ID, EVENT_ID, EVENT_NAME, EVENT_VERSION,
    USER_ID, ANONYMOUS_ID, SESSION_ID, EXPERIMENT_ID, VARIANT_ID,
    EVENT_TIMESTAMP, SENT_TIMESTAMP, RECEIVED_TIMESTAMP, SOURCE,
    ATTRIBUTES, PAYLOAD_HASH
  ) VALUES (
    source.INGESTION_ID, source.BATCH_ID, source.EVENT_ID,
    source.EVENT_NAME, source.EVENT_VERSION, source.USER_ID,
    source.ANONYMOUS_ID, source.SESSION_ID, source.EXPERIMENT_ID,
    source.VARIANT_ID, source.EVENT_TIMESTAMP, source.SENT_TIMESTAMP,
    source.RECEIVED_TIMESTAMP, source.SOURCE, source.ATTRIBUTES,
    source.PAYLOAD_HASH
  );

  MERGE INTO RAW.REJECTED_EVENTS AS target
  USING (
    SELECT
      INGESTION_ID,
      BATCH_ID,
      EVENT_ID,
      PAYLOAD,
      REJECTION_REASON AS REASON_CODE,
      OBJECT_CONSTRUCT_KEEP_NULL(
        'event_name', EVENT_NAME,
        'event_version', EVENT_VERSION,
        'payload_hash', PAYLOAD_HASH
      ) AS REASON_DETAILS
    FROM CLEAN.PRODUCT_EVENTS_CLASSIFIED
    WHERE BATCH_ID = :P_BATCH_ID
      AND REJECTION_REASON IS NOT NULL
  ) AS source
  ON target.INGESTION_ID = source.INGESTION_ID
  WHEN NOT MATCHED THEN INSERT (
    INGESTION_ID, BATCH_ID, EVENT_ID, PAYLOAD, REASON_CODE, REASON_DETAILS
  ) VALUES (
    source.INGESTION_ID, source.BATCH_ID, source.EVENT_ID, source.PAYLOAD,
    source.REASON_CODE, source.REASON_DETAILS
  );

  MERGE INTO CLEAN.PRODUCT_EVENTS_DEDUPLICATED AS target
  USING (
    SELECT
      validated.*,
      raw_event.INGESTED_AT
    FROM CLEAN.PRODUCT_EVENTS_VALIDATED AS validated
    JOIN RAW.PRODUCT_EVENTS AS raw_event
      ON validated.INGESTION_ID = raw_event.INGESTION_ID
    WHERE validated.BATCH_ID = :P_BATCH_ID
    QUALIFY ROW_NUMBER() OVER (
      PARTITION BY validated.EVENT_ID
      ORDER BY raw_event.INGESTED_AT, validated.INGESTION_ID
    ) = 1
  ) AS source
  ON target.EVENT_ID = source.EVENT_ID
  WHEN NOT MATCHED THEN INSERT (
    EVENT_ID, INGESTION_ID, BATCH_ID, EVENT_NAME, EVENT_VERSION,
    USER_ID, ANONYMOUS_ID, SESSION_ID, EXPERIMENT_ID, VARIANT_ID,
    EVENT_TIMESTAMP, SENT_TIMESTAMP, RECEIVED_TIMESTAMP, SOURCE,
    ATTRIBUTES, PAYLOAD_HASH, FIRST_INGESTED_AT
  ) VALUES (
    source.EVENT_ID, source.INGESTION_ID, source.BATCH_ID,
    source.EVENT_NAME, source.EVENT_VERSION, source.USER_ID,
    source.ANONYMOUS_ID, source.SESSION_ID, source.EXPERIMENT_ID,
    source.VARIANT_ID, source.EVENT_TIMESTAMP, source.SENT_TIMESTAMP,
    source.RECEIVED_TIMESTAMP, source.SOURCE, source.ATTRIBUTES,
    source.PAYLOAD_HASH, source.INGESTED_AT
  );

  SELECT COUNT(*) INTO :V_RAW_COUNT
  FROM RAW.PRODUCT_EVENTS
  WHERE BATCH_ID = :P_BATCH_ID;

  SELECT COUNT(*) INTO :V_VALIDATED_COUNT
  FROM CLEAN.PRODUCT_EVENTS_VALIDATED
  WHERE BATCH_ID = :P_BATCH_ID;

  SELECT COUNT(*) INTO :V_REJECTED_COUNT
  FROM RAW.REJECTED_EVENTS
  WHERE BATCH_ID = :P_BATCH_ID;

  SELECT GREATEST(COUNT(*) - COUNT(DISTINCT EVENT_ID), 0)
    INTO :V_DUPLICATE_COUNT
  FROM CLEAN.PRODUCT_EVENTS_VALIDATED
  WHERE BATCH_ID = :P_BATCH_ID;

  MERGE INTO RAW.INGESTION_AUDIT AS target
  USING (
    SELECT
      :P_BATCH_ID AS BATCH_ID,
      :P_CHANNEL_ID AS CHANNEL_ID,
      :P_FIRST_OFFSET AS FIRST_OFFSET,
      :P_LAST_OFFSET AS LAST_OFFSET,
      :P_RECORDS_SUBMITTED AS RECORDS_SUBMITTED,
      :V_RAW_COUNT AS RECORDS_COMMITTED
  ) AS source
  ON target.BATCH_ID = source.BATCH_ID
  WHEN MATCHED THEN UPDATE SET
    RECORDS_COMMITTED = source.RECORDS_COMMITTED,
    STATUS = 'COMMITTED',
    COMPLETED_AT = CURRENT_TIMESTAMP(),
    ERROR_CODE = NULL,
    ERROR_MESSAGE = NULL
  WHEN NOT MATCHED THEN INSERT (
    BATCH_ID, CHANNEL_ID, FIRST_OFFSET, LAST_OFFSET,
    RECORDS_SUBMITTED, RECORDS_COMMITTED, STATUS, STARTED_AT, COMPLETED_AT
  ) VALUES (
    source.BATCH_ID, source.CHANNEL_ID, source.FIRST_OFFSET,
    source.LAST_OFFSET, source.RECORDS_SUBMITTED, source.RECORDS_COMMITTED,
    'COMMITTED', CURRENT_TIMESTAMP(), CURRENT_TIMESTAMP()
  );

  MERGE INTO OBSERVABILITY.RECONCILIATION_RESULTS AS target
  USING (
    SELECT
      :P_BATCH_ID AS BATCH_ID,
      :P_RECORDS_SUBMITTED AS PRODUCER_COUNT,
      :V_RAW_COUNT AS RAW_COUNT,
      :V_VALIDATED_COUNT AS VALIDATED_COUNT,
      :V_REJECTED_COUNT AS REJECTED_COUNT,
      :V_DUPLICATE_COUNT AS DUPLICATE_COUNT,
      :P_RECORDS_SUBMITTED = :V_RAW_COUNT
        AND :V_RAW_COUNT = :V_VALIDATED_COUNT + :V_REJECTED_COUNT
        AS IS_BALANCED
  ) AS source
  ON target.BATCH_ID = source.BATCH_ID
  WHEN MATCHED THEN UPDATE SET
    PRODUCER_COUNT = source.PRODUCER_COUNT,
    RAW_COUNT = source.RAW_COUNT,
    VALIDATED_COUNT = source.VALIDATED_COUNT,
    REJECTED_COUNT = source.REJECTED_COUNT,
    DUPLICATE_COUNT = source.DUPLICATE_COUNT,
    IS_BALANCED = source.IS_BALANCED,
    CHECKED_AT = CURRENT_TIMESTAMP()
  WHEN NOT MATCHED THEN INSERT (
    BATCH_ID, PRODUCER_COUNT, RAW_COUNT, VALIDATED_COUNT,
    REJECTED_COUNT, DUPLICATE_COUNT, IS_BALANCED
  ) VALUES (
    source.BATCH_ID, source.PRODUCER_COUNT, source.RAW_COUNT,
    source.VALIDATED_COUNT, source.REJECTED_COUNT,
    source.DUPLICATE_COUNT, source.IS_BALANCED
  );

  RETURN OBJECT_CONSTRUCT(
    'raw_count', :V_RAW_COUNT,
    'validated_count', :V_VALIDATED_COUNT,
    'rejected_count', :V_REJECTED_COUNT,
    'duplicate_count', :V_DUPLICATE_COUNT,
    'is_balanced',
      :P_RECORDS_SUBMITTED = :V_RAW_COUNT
      AND :V_RAW_COUNT = :V_VALIDATED_COUNT + :V_REJECTED_COUNT
  );
END;
$$;

SELECT
  CURRENT_ROLE() AS ROLE,
  CURRENT_WAREHOUSE() AS WAREHOUSE,
  (SELECT COUNT(*) FROM CONFIG.EVENT_CONTRACTS WHERE CONTRACT_STATUS = 'ACTIVE')
    AS ACTIVE_CONTRACTS;
