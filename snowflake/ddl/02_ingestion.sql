CREATE TABLE IF NOT EXISTS CONFIG.EVENT_CONTRACTS (
  EVENT_NAME STRING NOT NULL,
  EVENT_VERSION NUMBER(9, 0) NOT NULL,
  REQUIRED_FIELDS ARRAY NOT NULL,
  DESCRIPTION STRING NOT NULL,
  CONTRACT_STATUS STRING NOT NULL DEFAULT 'ACTIVE',
  CREATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_EVENT_CONTRACTS PRIMARY KEY (EVENT_NAME, EVENT_VERSION) NOT ENFORCED
)
COMMENT = 'Versioned producer event contracts used by the validation pipeline';

MERGE INTO CONFIG.EVENT_CONTRACTS AS target
USING (
  SELECT COLUMN1 AS EVENT_NAME, COLUMN2 AS EVENT_VERSION,
         SPLIT(COLUMN3, ',') AS REQUIRED_FIELDS, COLUMN4 AS DESCRIPTION
  FROM VALUES
    ('experiment_assigned', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'An experiment variant was assigned.'),
    ('experiment_exposed', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'A subject experienced the assigned feature.'),
    ('restaurant_viewed', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'A restaurant detail page was viewed.'),
    ('item_added', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'An item was added to a cart.'),
    ('checkout_started', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'The checkout flow began.'),
    ('order_completed', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'An order was paid and created.'),
    ('order_cancelled', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'An order was cancelled.'),
    ('payment_failed', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'A payment attempt failed.'),
    ('delivery_completed', 1, 'event_id,event_name,event_version,user_id,session_id,experiment_id,variant_id,event_timestamp,received_timestamp,source,attributes', 'An order was delivered.')
) AS source
ON target.EVENT_NAME = source.EVENT_NAME
AND target.EVENT_VERSION = source.EVENT_VERSION
WHEN MATCHED THEN UPDATE SET
  REQUIRED_FIELDS = source.REQUIRED_FIELDS,
  DESCRIPTION = source.DESCRIPTION,
  UPDATED_AT = CURRENT_TIMESTAMP()
WHEN NOT MATCHED THEN INSERT (
  EVENT_NAME, EVENT_VERSION, REQUIRED_FIELDS, DESCRIPTION
) VALUES (
  source.EVENT_NAME, source.EVENT_VERSION, source.REQUIRED_FIELDS, source.DESCRIPTION
);

CREATE TABLE IF NOT EXISTS RAW.PRODUCT_EVENTS (
  INGESTION_ID STRING NOT NULL DEFAULT UUID_STRING(),
  BATCH_ID STRING NOT NULL,
  CHANNEL_ID STRING NOT NULL,
  STREAM_OFFSET NUMBER(38, 0) NOT NULL,
  EVENT_ID STRING,
  EVENT_NAME STRING,
  EVENT_VERSION NUMBER(9, 0),
  EVENT_TIMESTAMP TIMESTAMP_TZ,
  RECEIVED_TIMESTAMP TIMESTAMP_TZ,
  SOURCE STRING,
  PAYLOAD VARIANT NOT NULL,
  PAYLOAD_HASH STRING NOT NULL,
  INGESTED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT UQ_PRODUCT_EVENTS_OFFSET
    UNIQUE (CHANNEL_ID, STREAM_OFFSET) NOT ENFORCED
)
COMMENT = 'Immutable producer payloads plus source and offset metadata';

CREATE PIPE IF NOT EXISTS RAW.PRODUCT_EVENTS_STREAMING
  COMMENT = 'High-performance Snowpipe Streaming entry point for product events'
AS COPY INTO RAW.PRODUCT_EVENTS (
  INGESTION_ID,
  BATCH_ID,
  CHANNEL_ID,
  STREAM_OFFSET,
  EVENT_ID,
  EVENT_NAME,
  EVENT_VERSION,
  EVENT_TIMESTAMP,
  RECEIVED_TIMESTAMP,
  SOURCE,
  PAYLOAD,
  PAYLOAD_HASH,
  INGESTED_AT
)
FROM (
  SELECT
    UUID_STRING(),
    $1:batch_id::STRING,
    $1:channel_id::STRING,
    TRY_TO_NUMBER($1:stream_offset::STRING),
    $1:event_id::STRING,
    $1:event_name::STRING,
    TRY_TO_NUMBER($1:event_version::STRING),
    TRY_TO_TIMESTAMP_TZ($1:event_timestamp::STRING),
    TRY_TO_TIMESTAMP_TZ($1:received_timestamp::STRING),
    $1:source::STRING,
    $1:payload::VARIANT,
    $1:payload_hash::STRING,
    CURRENT_TIMESTAMP()
  FROM TABLE(DATA_SOURCE(TYPE => 'STREAMING'))
);

CREATE STREAM IF NOT EXISTS RAW.PRODUCT_EVENTS_CHANGES
  ON TABLE RAW.PRODUCT_EVENTS
  APPEND_ONLY = TRUE
  COMMENT = 'Unprocessed raw events for validation, quarantine, and deduplication';

