-- Phase 5: versioned metric artifacts plus explainable rollout decisions.
-- Run as GUARDRAIL_ENGINEER after Phase 4 setup.

USE ROLE GUARDRAIL_ENGINEER;
USE WAREHOUSE GUARDRAIL_TRANSFORM_WH;
USE DATABASE GUARDRAIL;

CREATE TABLE IF NOT EXISTS CONTROL.METRIC_DEFINITIONS (
  ARTIFACT_ID STRING NOT NULL,
  METRIC_NAME STRING NOT NULL,
  METRIC_VERSION NUMBER(9, 0) NOT NULL,
  DEFINITION_HASH STRING NOT NULL,
  DEFINITION VARIANT NOT NULL,
  COMPILED_SQL STRING NOT NULL,
  COMPILED_SQL_HASH STRING NOT NULL,
  STATUS STRING NOT NULL,
  COMPILED_AT TIMESTAMP_TZ NOT NULL,
  UPDATED_AT TIMESTAMP_LTZ NOT NULL DEFAULT CURRENT_TIMESTAMP(),
  CONSTRAINT PK_METRIC_DEFINITIONS
    PRIMARY KEY (METRIC_NAME, METRIC_VERSION) NOT ENFORCED
)
COMMENT = 'Validated, versioned metric definitions and deterministic compiled Snowflake SQL';

CREATE TABLE IF NOT EXISTS CONTROL.ROLLOUT_DECISIONS (
  DECISION_ID STRING NOT NULL,
  EXPERIMENT_ID STRING NOT NULL,
  ALLOCATION_VERSION NUMBER(9, 0) NOT NULL,
  PREVIOUS_STATE STRING NOT NULL,
  RECOMMENDED_STATE STRING NOT NULL,
  DECISION STRING NOT NULL,
  DECISION_REASON STRING NOT NULL,
  ANALYSIS_STATUS STRING NOT NULL,
  ANALYSIS_SNAPSHOT_ID STRING,
  HEALTH_SNAPSHOT_ID STRING,
  POLICY_VERSION STRING NOT NULL,
  POLICY VARIANT NOT NULL,
  GUARDRAIL_EVIDENCE VARIANT NOT NULL,
  GUARDRAIL_CHECKS VARIANT NOT NULL,
  CREATED_AT TIMESTAMP_TZ NOT NULL,
  CONSTRAINT PK_ROLLOUT_DECISIONS PRIMARY KEY (DECISION_ID) NOT ENFORCED
)
COMMENT = 'Immutable rollout recommendations with exact analysis and policy evidence';

CREATE TABLE IF NOT EXISTS CONTROL.STATE_TRANSITIONS (
  TRANSITION_ID STRING NOT NULL,
  DECISION_ID STRING NOT NULL,
  EXPERIMENT_ID STRING NOT NULL,
  ALLOCATION_VERSION NUMBER(9, 0) NOT NULL,
  PREVIOUS_STATE STRING NOT NULL,
  NEW_STATE STRING NOT NULL,
  DECISION STRING NOT NULL,
  DECISION_REASON STRING NOT NULL,
  ANALYSIS_SNAPSHOT_ID STRING,
  HEALTH_SNAPSHOT_ID STRING,
  POLICY_VERSION STRING NOT NULL,
  REQUESTED_BY STRING NOT NULL,
  APPROVED_BY STRING NOT NULL,
  CREATED_AT TIMESTAMP_TZ NOT NULL,
  CONSTRAINT PK_STATE_TRANSITIONS PRIMARY KEY (TRANSITION_ID) NOT ENFORCED,
  CONSTRAINT FK_TRANSITION_DECISION FOREIGN KEY (DECISION_ID)
    REFERENCES CONTROL.ROLLOUT_DECISIONS (DECISION_ID) NOT ENFORCED
)
COMMENT = 'Immutable approved state-transition history linked to rollout decisions';

SELECT
  CURRENT_ROLE(),
  CURRENT_WAREHOUSE(),
  COUNT_IF(TABLE_NAME IN (
    'METRIC_DEFINITIONS',
    'ROLLOUT_DECISIONS',
    'STATE_TRANSITIONS'
  ))
FROM GUARDRAIL.INFORMATION_SCHEMA.TABLES
WHERE TABLE_SCHEMA = 'CONTROL';
