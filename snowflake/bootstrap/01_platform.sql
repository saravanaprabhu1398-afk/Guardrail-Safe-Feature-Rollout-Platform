-- One-time Guardrail platform bootstrap. Run in Snowsight as ACCOUNTADMIN.
-- Warehouses are created suspended and consume no credits while suspended.

USE ROLE ACCOUNTADMIN;

CREATE RESOURCE MONITOR IF NOT EXISTS GUARDRAIL_DEV_MONITOR
  WITH CREDIT_QUOTA = 20
  FREQUENCY = MONTHLY
  START_TIMESTAMP = IMMEDIATELY
  TRIGGERS
    ON 75 PERCENT DO NOTIFY
    ON 90 PERCENT DO SUSPEND
    ON 100 PERCENT DO SUSPEND_IMMEDIATE;

CREATE WAREHOUSE IF NOT EXISTS GUARDRAIL_INGEST_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Guardrail ingestion and development warehouse';

CREATE WAREHOUSE IF NOT EXISTS GUARDRAIL_TRANSFORM_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE
  COMMENT = 'Guardrail transformation warehouse';

ALTER WAREHOUSE GUARDRAIL_INGEST_WH
  SET RESOURCE_MONITOR = GUARDRAIL_DEV_MONITOR;
ALTER WAREHOUSE GUARDRAIL_TRANSFORM_WH
  SET RESOURCE_MONITOR = GUARDRAIL_DEV_MONITOR;

CREATE DATABASE IF NOT EXISTS GUARDRAIL
  DATA_RETENTION_TIME_IN_DAYS = 1
  COMMENT = 'Guardrail experimentation data platform';

CREATE SCHEMA IF NOT EXISTS GUARDRAIL.CONFIG;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.RAW;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.CLEAN;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.CORE;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.METRICS;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.CONTROL;
CREATE SCHEMA IF NOT EXISTS GUARDRAIL.OBSERVABILITY;

GRANT USAGE, OPERATE ON WAREHOUSE GUARDRAIL_INGEST_WH
  TO ROLE GUARDRAIL_ENGINEER;
GRANT USAGE, OPERATE ON WAREHOUSE GUARDRAIL_TRANSFORM_WH
  TO ROLE GUARDRAIL_ENGINEER;
GRANT USAGE ON DATABASE GUARDRAIL TO ROLE GUARDRAIL_ENGINEER;
GRANT USAGE ON ALL SCHEMAS IN DATABASE GUARDRAIL
  TO ROLE GUARDRAIL_ENGINEER;

GRANT CREATE TABLE, CREATE VIEW, CREATE STAGE, CREATE FILE FORMAT,
      CREATE PIPE, CREATE STREAM, CREATE TASK, CREATE DYNAMIC TABLE,
      CREATE FUNCTION, CREATE PROCEDURE
  ON ALL SCHEMAS IN DATABASE GUARDRAIL
  TO ROLE GUARDRAIL_ENGINEER;

GRANT EXECUTE TASK ON ACCOUNT TO ROLE GUARDRAIL_ENGINEER;

USE ROLE GUARDRAIL_ENGINEER;
USE WAREHOUSE GUARDRAIL_INGEST_WH;
USE DATABASE GUARDRAIL;
USE SCHEMA RAW;

SELECT CURRENT_USER(), CURRENT_ROLE(), CURRENT_WAREHOUSE(),
       CURRENT_DATABASE(), CURRENT_SCHEMA();
